<style>:root{<?= $vars ?>}</style>
</head>
<body>
<div class="login-wrap">
<div style="width:100%;max-width:640px">
    <div class="text-center mb-3">
        <div class="login-logo">⚽</div>
        <h1>Plataforma de Ligas de Fútbol</h1>
        <p class="muted">Asistente de instalación</p>
    </div>

    <?php if ($alreadyInstalled): ?>
        <div class="card card-pad-lg text-center">
            <div class="es-icon">✅</div>
            <h2>Ya está instalado</h2>
            <p class="muted">La plataforma ya fue instalada. Por seguridad, elimina la carpeta <code>/install</code>.</p>
            <a class="btn" href="../admin/login.php">Ir al panel</a>
        </div>
    <?php elseif ($done): ?>
        <div class="card card-pad-lg text-center">
            <div class="es-icon">🎉</div>
            <h2>¡Instalación completada!</h2>
            <p class="muted">Se crearon las tablas, el Super Administrador, los roles, permisos y los 10 temas visuales.
            No se cargó ninguna liga, equipo ni jugador de prueba.</p>
            <div class="alert alert-warning" style="text-align:left"><span><strong>Importante:</strong> Elimina la carpeta <code>/install</code> del servidor para mayor seguridad.</span></div>
            <a class="btn btn-lg" href="../admin/login.php">Acceder al panel</a>
        </div>
    <?php else: ?>
        <?php foreach ($errors as $er): ?><div class="alert alert-danger"><span><?= e($er) ?></span></div><?php endforeach; ?>

        <div class="card mb-3">
            <h3 style="margin-top:0">Requisitos del servidor</h3>
            <div class="detail-list">
                <?php foreach ($requirements as $label => $ok): ?>
                    <div class="row"><span class="k"><?= e($label) ?></span><span class="v"><?= $ok ? '<span class="badge badge-success">OK</span>' : '<span class="badge badge-danger">Falta</span>' ?></span></div>
                <?php endforeach; ?>
            </div>
        </div>

        <form method="post" class="card card-pad-lg">
            <h3 style="margin-top:0">Base de datos</h3>
            <div class="form-row">
                <div class="field"><label>Host</label><input class="input" name="db_host" value="<?= e($_POST['db_host'] ?? 'localhost') ?>" required></div>
                <div class="field"><label>Puerto</label><input class="input" name="db_port" value="<?= e($_POST['db_port'] ?? '3306') ?>"></div>
            </div>
            <div class="field"><label>Nombre de la base de datos</label><input class="input" name="db_name" value="<?= e($_POST['db_name'] ?? '') ?>" required></div>
            <div class="form-row">
                <div class="field"><label>Usuario</label><input class="input" name="db_user" value="<?= e($_POST['db_user'] ?? '') ?>" required></div>
                <div class="field"><label>Contraseña</label><input class="input" type="password" name="db_pass"></div>
            </div>

            <h3 class="mt-3">Super Administrador</h3>
            <div class="form-row">
                <div class="field"><label>Nombre completo</label><input class="input" name="admin_name" value="<?= e($_POST['admin_name'] ?? '') ?>" required></div>
                <div class="field"><label>Usuario</label><input class="input" name="admin_username" value="<?= e($_POST['admin_username'] ?? '') ?>" required></div>
            </div>
            <div class="field"><label>Correo electrónico</label><input class="input" type="email" name="admin_email" value="<?= e($_POST['admin_email'] ?? '') ?>" required></div>
            <div class="field"><label>Contraseña (mín. 8 caracteres)</label><input class="input" type="password" name="admin_password" required></div>

            <button class="btn btn-lg btn-block mt-2" type="submit"<?= $reqOk ? '' : ' disabled' ?>>Instalar plataforma</button>
            <?php if (!$reqOk): ?><p class="help text-center" style="color:var(--c-danger)">Corrige los requisitos faltantes antes de continuar.</p><?php endif; ?>
        </form>
    <?php endif; ?>
</div>
</div>
